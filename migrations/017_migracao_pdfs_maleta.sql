-- =====================================================================
-- PDFs de cada movimentação da maleta (criação e ajustes)
--
-- O app gera, a cada criação de maleta e a cada adição/remoção de itens, dois PDFs
-- (descrição padrão e produto_descricao_site), guarda no bucket público `pdf_maletas`
-- e registra o caminho em parcerias_envio_pdfs. Os movimentos de um mesmo ajuste
-- apontam para o PDF pela coluna parcerias_envio_movimentos.pdf_id.
--
-- Pode ser executado mais de uma vez (idempotente).
-- =====================================================================

-- 1) Tabela de PDFs. O tipo de envio_id acompanha o tipo de parcerias_envios.id (bigint ou uuid).
do $$
declare
  tipo_id text;
begin
  select format_type(a.atttypid, a.atttypmod)
    into tipo_id
    from pg_attribute a
   where a.attrelid = 'public.parcerias_envios'::regclass
     and a.attname = 'id'
     and not a.attisdropped;

  execute format($f$
    create table if not exists public.parcerias_envio_pdfs (
      id             bigint generated by default as identity primary key,
      envio_id       %s not null references public.parcerias_envios(id) on delete cascade,
      evento         text not null check (evento in ('criacao', 'ajuste')),
      motivo         text,
      total_itens    integer,
      total_pecas    numeric,
      caminho_padrao text,
      caminho_site   text,
      criado_em      timestamptz not null default now()
    )
  $f$, tipo_id);
end $$;

create index if not exists idx_parcerias_envio_pdfs_envio
  on public.parcerias_envio_pdfs (envio_id, id);

-- 2) Liga os movimentos ao PDF do ajuste em que foram gravados
alter table public.parcerias_envio_movimentos
  add column if not exists pdf_id bigint
  references public.parcerias_envio_pdfs(id) on delete set null;

-- 3) Acesso da tabela para usuários logados
alter table public.parcerias_envio_pdfs enable row level security;

drop policy if exists "parcerias_envio_pdfs_autenticados" on public.parcerias_envio_pdfs;
create policy "parcerias_envio_pdfs_autenticados"
  on public.parcerias_envio_pdfs
  for all
  to authenticated
  using (true)
  with check (true);

-- 4) Bucket público (leitura por link) + envio/remoção só por usuários logados
insert into storage.buckets (id, name, public)
values ('pdf_maletas', 'pdf_maletas', true)
on conflict (id) do update set public = true;

drop policy if exists "pdf_maletas_insert_autenticados" on storage.objects;
create policy "pdf_maletas_insert_autenticados"
  on storage.objects
  for insert
  to authenticated
  with check (bucket_id = 'pdf_maletas');

drop policy if exists "pdf_maletas_delete_autenticados" on storage.objects;
create policy "pdf_maletas_delete_autenticados"
  on storage.objects
  for delete
  to authenticated
  using (bucket_id = 'pdf_maletas');
